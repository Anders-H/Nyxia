# Extract compact image data from ImageConverter's standalone CBM Prg Studio exports.
# Run again after regenerating Tooling/CbmSource/*.asm.
$ErrorActionPreference = 'Stop'
$sourceFolder = Join-Path $PSScriptRoot '../../Tooling/CbmSource'
$names = @('01darth','02sam','03back')
$images = @()
function Read-Bytes([string]$text, [string]$label, [int]$expected) {
    $body = [regex]::Match($text, '(?m)^' + $label + '\r?\n(?<body>(?:[ \t]+BYTE [^\r\n]+\r?\n)+)').Groups['body'].Value
    $bytes = [byte[]]@([regex]::Matches($body, '\$([0-9A-Fa-f]{2})') | ForEach-Object { [Convert]::ToByte($_.Groups[1].Value,16) })
    if ($bytes.Length -ne $expected) { throw "$label must contain $expected bytes, got $($bytes.Length)." }
    return ,$bytes
}
foreach ($name in $names) {
    $text = Get-Content (Join-Path $sourceFolder ($name + '.asm')) -Raw
    $bitmap = Read-Bytes $text 'BitmapData' 8192
    $sprites = Read-Bytes $text 'SpriteData' 512
    $screen = Read-Bytes $text 'ScreenData' 1000
    for ($y=0; $y -lt 25; $y++) { for ($x=0; $x -lt 40; $x++) {
        $expected = if ($y -ge 2 -and $y -lt 8 -and $x -ge 14 -and $x -lt 26) { 0x5b } else { 0x66 }
        if ($screen[$y*40+$x] -ne $expected) { throw "$name has an incompatible screen layout." }
    } }
    $compact = [byte[]]::new(576)
    for ($row=0; $row -lt 6; $row++) { [Array]::Copy($bitmap, ((2+$row)*40+14)*8, $compact, $row*96, 96) }
    $images += @{Name=$name; Bitmap=$compact; Sprites=$sprites}
}
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('; Generated by Export-Images.ps1. Do not edit image bytes manually.')
for ($i=0; $i -lt 3; $i++) {
    [void]$output.AppendLine("; $($names[$i]): copy only the image area, then the eight sprites.")
    [void]$output.AppendLine("CopyImage$i")
    [void]$output.AppendLine('        ldx #$00')
    [void]$output.AppendLine("CopyBitmap$i")
    for ($row=0; $row -lt 6; $row++) {
        [void]$output.AppendLine(('        lda Image{0}Bitmap+${1:X4},x' -f $i,($row*96)))
        [void]$output.AppendLine(('        sta ${0:X4},x' -f (0x2000+((2+$row)*40+14)*8)))
    }
    [void]$output.AppendLine('        inx')
    [void]$output.AppendLine('        cpx #$60')
    [void]$output.AppendLine("        bne CopyBitmap$i")
    [void]$output.AppendLine('        ldx #$00')
    [void]$output.AppendLine("CopySprites$i")
    # Eight 64-byte chunks avoid source page crossings and finish before the
    # next bitmap IRQ even on NTSC, including VIC badline bus stealing.
    for ($sprite=0; $sprite -lt 8; $sprite++) {
        [void]$output.AppendLine(('        lda Image{0}Sprites+${1:X4},x' -f $i,($sprite*64)))
        [void]$output.AppendLine(('        sta ${0:X4},x' -f (0x0c00+$sprite*64)))
    }
    [void]$output.AppendLine('        inx')
    [void]$output.AppendLine('        cpx #$40')
    [void]$output.AppendLine("        bne CopySprites$i")
    [void]$output.AppendLine('        rts')
}
[void]$output.AppendLine('* = $4000')
for ($i=0; $i -lt 3; $i++) {
    foreach ($kind in @('Bitmap','Sprites')) {
        [void]$output.AppendLine("Image$i$kind")
        $data = $images[$i][$kind]
        for($offset=0; $offset -lt $data.Length; $offset+=16) {
            $row = $data[$offset..([Math]::Min($offset+15,$data.Length-1))] | ForEach-Object { '${0:X2}' -f $_ }
            [void]$output.AppendLine('        BYTE ' + ($row -join ','))
        }
    }
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'images.asm'),$output.ToString(),[Text.Encoding]::ASCII)
Write-Output 'Generated images.asm: 3 images, 1088 bytes per image.'
